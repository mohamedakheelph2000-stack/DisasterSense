#!/bin/bash
set -e

# Setup 3GB Swap space so t3.micro has plenty of virtual memory for Docker builds
if [ ! -f /swapfile ]; then
    fallocate -l 3G /swapfile
    chmod 600 /swapfile
    mkswap /swapfile
    swapon /swapfile
    echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

# Update and install Docker
apt-get update -y
apt-get install -y apt-transport-https ca-certificates curl software-properties-common git

# Add Docker's official GPG key
install -m 0755 -d /etc/apt/keyrings
curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
chmod a+r /etc/apt/keyrings/docker.asc

# Add Docker repository
echo \
  "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu \
  $(. /etc/os-release && echo "$VERSION_CODENAME") stable" | \
  tee /etc/apt/sources.list.d/docker.list > /dev/null

apt-get update -y
apt-get install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin

systemctl enable docker
systemctl start docker
usermod -aG docker ubuntu

# Setup deployment directory
mkdir -p /home/ubuntu/DisasterSense
chown -R ubuntu:ubuntu /home/ubuntu/DisasterSense

echo "DisasterSense EC2 host initialized successfully."
